def _normalize_effect_bundle(bundle: dict[str, object]) -> dict[str, object]:
    normalized = copy.deepcopy(bundle)
    normalized["trust"] = {
        canonical_role_slot_id(npc_id): value for npc_id, value in dict(normalized.get("trust", {})).items()
    }
    normalized["stress"] = {
        canonical_role_slot_id(npc_id): value for npc_id, value in dict(normalized.get("stress", {})).items()
    }
    normalized["hints"] = [
        {**hint, "npcId": canonical_role_slot_id(str(hint["npcId"]))}
        for hint in list(normalized.get("hints", []))
    ]
    normalized["weaknesses"] = [
        {**weakness, "npcId": canonical_role_slot_id(str(weakness["npcId"]))}
        for weakness in list(normalized.get("weaknesses", []))
    ]
    return normalized


def _normalize_branch(branch: dict[str, object]) -> dict[str, object]:
    normalized = copy.deepcopy(branch)
    normalized["focusNpcIds"] = [canonical_role_slot_id(str(npc_id)) for npc_id in list(branch.get("focusNpcIds", []))]
    selectors = copy.deepcopy(dict(branch.get("selectors", {})))
    if selectors.get("secretStates"):
        selectors["secretStates"] = {
            canonical_role_slot_id(str(npc_id)): states for npc_id, states in dict(selectors["secretStates"]).items()
        }
    if selectors.get("knownWeaknessNpcIds"):
        selectors["knownWeaknessNpcIds"] = [
            canonical_role_slot_id(str(npc_id)) for npc_id in list(selectors["knownWeaknessNpcIds"])
        ]
    normalized["selectors"] = selectors
    normalized["fx"] = {
        outcome: _normalize_effect_bundle(effect_bundle)
        for outcome, effect_bundle in dict(branch.get("fx", {})).items()
    }
    return normalized


def _normalize_event_blueprints(raw_blueprints: list[dict[str, object]]) -> list[dict[str, object]]:
    normalized: list[dict[str, object]] = []
    for blueprint in raw_blueprints:
        item = copy.deepcopy(blueprint)
        item["branches"] = [_normalize_branch(branch) for branch in list(blueprint.get("branches", []))]
        normalized.append(item)
    return normalized


